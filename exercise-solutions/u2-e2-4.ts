// This program stores a year, month, and day in variables and outputs
// them as a date in the format YYYY/MM/DD using one console.log().

let year: number = 2023;
let month: number = 1;
let day: number = 20;

// "/0" is a string literal, so the month always shows two digits here
console.log(year + "/0" + month + "/" + day);
